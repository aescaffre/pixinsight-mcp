#!/usr/bin/env node
// Writes pjsr/mcp-solver-paths.jsh: the #include lines for PixInsight's ImageSolver scripts, which the watcher
// needs for its plate-solve fallback. PJSR cannot locate src/scripts by itself, and hard-coding the macOS install
// path broke other machines/OSes (Windows report, 2026-11-08).
// PixInsight folder: --pi-dir <dir> | env PIXINSIGHT_DIR | platform default
//   macOS /Applications/PixInsight, Windows C:/Program Files/PixInsight, Linux /opt/PixInsight.
// If ImageSolver is not found, an empty include is written: the watcher still works, only the plate-solve fallback
// (used when masters carry no WCS) is unavailable.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'pjsr', 'mcp-solver-paths.jsh');
const argDir = (() => { const i = process.argv.indexOf('--pi-dir'); return i > 0 ? process.argv[i + 1] : null; })();
const defaults = { darwin: '/Applications/PixInsight', win32: 'C:/Program Files/PixInsight', linux: '/opt/PixInsight' };
const candidates = [argDir, process.env.PIXINSIGHT_DIR, defaults[process.platform], ...Object.values(defaults)].filter(Boolean);
const fwd = (p) => p.replace(/\\/g, '/');
let found = null;
for (const d of candidates) {
  const dir = path.join(d, 'src', 'scripts', 'ImageSolver');
  if (fs.existsSync(path.join(dir, 'ImageSolverEngine.js')) && fs.existsSync(path.join(dir, 'ImageSolverDialog.js'))) { found = fwd(dir); break; }
}
const head = `// Generated by scripts/setup-watcher.mjs on ${new Date().toISOString()} (${process.platform}). Do not edit; re-run the script.\n`;
const body = found
  ? `#include "${found}/ImageSolverDialog.js"\n#include "${found}/ImageSolverEngine.js"\n`
  : `// ImageSolver not found (tried: ${candidates.map(fwd).join(', ')}). Plate-solve fallback disabled.\n`;
fs.writeFileSync(out, head + body);
console.log(found ? `ImageSolver: ${found} -> ${out}` : `ImageSolver NOT found; wrote an empty include (${out}). Set PIXINSIGHT_DIR or pass --pi-dir.`);
